def render(text):
    """Render a string as five rows of block glyphs. Unknown characters drop out."""
    rows = ["", "", "", "", ""]
    for char in text.upper():
        glyph = GLYPHS.get(char)
        if glyph is None:
            continue
        for i in range(5):
            rows[i] += glyph[i] + " "
    return [row[:-1] for row in rows] if rows[0] else ["", "", "", "", ""]


def width(text):
    """Rendered width of `text` in columns."""
    return len(render(text)[0])
